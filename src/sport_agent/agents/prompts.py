            "3. 如涉及就医指征，明确建议就医\n"
            "4. 用户画像里已给出的字段必须使用，不得声称该信息未知。"
            "例如画像给出年龄时，必须按田中公式 HRmax = 208 - 0.7×年龄 估算最大心率并给出具体靶心率区间；"
